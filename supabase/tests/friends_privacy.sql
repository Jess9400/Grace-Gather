-- Transactional integration test. Synthetic users and messages are rolled back.
begin;
select set_config('test.friend_a',gen_random_uuid()::text,true),set_config('test.friend_b',gen_random_uuid()::text,true),set_config('test.friend_c',gen_random_uuid()::text,true);
insert into auth.users(id,email,email_confirmed_at) select current_setting(k)::uuid,current_setting(k)||'@example.invalid',now() from unnest(array['test.friend_a','test.friend_b','test.friend_c']) k;
set local role authenticated;
do $$
declare a uuid:=current_setting('test.friend_a')::uuid; b uuid:=current_setting('test.friend_b')::uuid; c uuid:=current_setting('test.friend_c')::uuid;
 lid uuid; mid uuid; blocked boolean; data jsonb;
begin
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform public.friends_command('directory','{"name":"Fixture Alpha","discoverable":true}');
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.friends_command('directory','{"name":"Fixture Beta","discoverable":true}');
 perform set_config('request.jwt.claim.sub',c::text,true);
 perform public.friends_command('directory','{"name":"Fixture Hidden","discoverable":false}');
 perform set_config('request.jwt.claim.sub',a::text,true);
 data:=public.friends_command('search','{"query":"Fixture Hidden"}');
 if jsonb_array_length(data)<>0 then raise exception 'Opt-out member exposed';end if;
 perform public.friends_command('request',jsonb_build_object('peer',b));
 data:=public.friends_command('list');lid:=(data->'links'->0->>'id')::uuid;
 blocked:=false;
 begin perform public.friends_command('send',jsonb_build_object('id',lid,'body','Before acceptance'));exception when others then blocked:=true;end;
 if not blocked then raise exception 'Pending relationship can send';end if;
 blocked:=false;
 begin perform public.friends_command('accept',jsonb_build_object('id',lid));exception when others then blocked:=true;end;
 if not blocked then raise exception 'Sender can accept own request';end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.friends_command('accept',jsonb_build_object('id',lid));
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform public.friends_command('send',jsonb_build_object('id',lid,'body','Synthetic private message'));
 perform set_config('request.jwt.claim.sub',b::text,true);
 data:=public.friends_command('messages',jsonb_build_object('id',lid));
 if jsonb_array_length(data)<>1 or (data->0->>'mine')::boolean then raise exception 'Recipient cannot read message correctly';end if;
 mid:=(data->0->>'id')::uuid;
 perform public.friends_command('report',jsonb_build_object('id',lid,'message',mid,'reason','Synthetic permission test'));
 perform set_config('request.jwt.claim.sub',c::text,true);
 blocked:=false;
 begin perform public.friends_command('messages',jsonb_build_object('id',lid));exception when others then blocked:=true;end;
 if not blocked then raise exception 'Third party can read chat';end if;
 blocked:=false;
 begin perform public.friends_command('send',jsonb_build_object('id',lid,'body','Intruder'));exception when others then blocked:=true;end;
 if not blocked then raise exception 'Third party can send chat';end if;
 blocked:=false;
 begin perform public.friends_command('reports');exception when others then blocked:=true;end;
 if not blocked then raise exception 'Nonstaff can read reports';end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.friends_command('block',jsonb_build_object('peer',a));
 perform set_config('request.jwt.claim.sub',a::text,true);
 blocked:=false;
 begin perform public.friends_command('send',jsonb_build_object('id',lid,'body','After block'));exception when others then blocked:=true;end;
 if not blocked then raise exception 'Blocked peer can send';end if;
 if jsonb_array_length(public.friends_command('search','{"query":"Fixture Beta"}'))<>0 then raise exception 'Blocked peer discoverable';end if;
 if has_table_privilege('authenticated','private.friend_messages','SELECT') then raise exception 'Direct message table exposed';end if;
 if has_function_privilege('anon','public.friends_command(text,jsonb)','EXECUTE') then raise exception 'Anonymous command exposed';end if;
end $$;
reset role;
select 'PASS: opt-in search, acceptance, recipient access, third-party isolation, reporting, blocking and grants' as result;
rollback;
