#!/usr/bin/env python3
"""Import reviewed, pinned publisher USFX archives without translating Scripture.
Usage: python3 scripts/import-multilingual-bibles.py /path/to/archives
"""
import importlib.util, json, hashlib, sys
from pathlib import Path
from zipfile import ZipFile
import xml.etree.ElementTree as ET
root=Path(__file__).resolve().parent.parent
spec=importlib.util.spec_from_file_location('reader',root/'scripts/import-bible-collections.py')
reader=importlib.util.module_from_spec(spec); spec.loader.exec_module(reader)
sources={
 'blivre': ('porbr2018','pt','cf13631e6f9f1378d2298d300862d38dfa5bce02deef1eeb1c5006c1c5084597'),
 'rv1909': ('spaRV1909','es','6fd2db9b7b865f8f0c7eeb9ca859a52e36d532ca8d5a35fbf746310436197b48'),
 'synodal': ('russyn','ru','acd200046b4a4cb9bca8ca375544bc9d58ae10dc64f1862a2b7b73e225931a77'),
}
catalog=json.loads((root/'mobile/src/generated/catalog.json').read_text())
for key,(source,language,pin) in sources.items():
 archive=Path(sys.argv[1])/f'{key}.zip'
 assert hashlib.sha256(archive.read_bytes()).hexdigest()==pin, 'Publisher archive changed; review before updating the pin'
 edition=next(e for e in catalog['editions'] if e['id']==key)
 out=root/'mobile/src/generated'/f'bible-{key}';out.mkdir(exist_ok=True)
 with ZipFile(archive) as z:
  xml=ET.fromstring(z.read(f'{source}_usfx.xml'))
  names={b.attrib['code']:b.attrib['short'] for b in ET.fromstring(z.read('BookNames.xml'))}
  (out/'publisher-rights.html').write_bytes(z.read('copr.htm'))
 books=[];loaders=[]
 for book in xml.findall('book'):
  code=book.attrib['id']; chapters=reader.parse_book(book,code, {'pt':'O arquivo da editora não contém texto neste marcador de versículo.','es':'El archivo del editor no contiene texto en este marcador de versículo.','ru':'В файле издателя у этого номера стиха нет текста.'}[language], include_book_tails=True)
  meta={'code':code,'name':names[code],'chapters':len(chapters),'verses':sum(map(len,chapters.values())),
    'sourceBaseUrl':f'https://ebible.org/{source}/','sourceChapterDigits':3 if code=='PSA' else 2,
    'sourceEdition':edition['name'],'sourceAttribution':edition['attribution'],'sourceLicenseUrl':edition['licenseUrl']}
  reader.write_json(out/f'{code}.json',{'book':meta,'chapters':chapters})
  books.append(meta);loaders.append(f'  "{code}": () => require("./{code}.json"),')
 assert len(books)==66
 reader.write_json(out/'index.json',{'id':key,'edition':edition['name'],'language':language,'traditions':edition['traditions'],
  'attribution':edition['attribution'],'licenseUrl':edition['licenseUrl'], 'publisherRightsUrl':f'https://ebible.org/{source}/copyright.htm',
  'sourceUrl':f'https://ebible.org/Scriptures/{source}_usfx.zip','sourceSha256':pin,'books':books,
  'coverageNote':'66 books from the publisher. This source does not include the additional Orthodox books.' if key=='synodal' else '66-book collection from the publisher. Verse wording and numbering preserved; notes kept separately.'},True)
 (out/'loaders.ts').write_text('// Generated by scripts/import-multilingual-bibles.py\nexport const bookLoaders = {\n'+'\n'.join(loaders)+'\n};\n')
 print(key,len(books),sum(b['verses'] for b in books))
