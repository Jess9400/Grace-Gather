// Build a finite set of attributed Scripture narratives from the bundled,
// licensed Brazilian Portuguese Bible. This never generates personal stories.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const selections = [
  ["LUK",10,25,37,"O bom samaritano"], ["LUK",15,3,7,"A ovelha perdida"],
  ["LUK",15,11,32,"O filho que voltou para casa"], ["LUK",19,1,10,"Jesus encontra Zaqueu"],
  ["LUK",10,38,42,"Marta e Maria recebem Jesus"], ["LUK",8,22,25,"Jesus acalma a tempestade"],
  ["LUK",7,11,17,"Jesus encontra uma mãe em Naim"], ["LUK",8,40,56,"A filha de Jairo"],
  ["LUK",24,13,35,"O caminho de Emaús"], ["LUK",5,1,11,"A pesca no lago"],
  ["JHN",2,1,11,"As bodas em Caná"], ["JHN",4,5,26,"Jesus e a mulher junto ao poço"],
  ["JHN",6,1,14,"Os pães e os peixes"], ["JHN",9,1,12,"O homem que nasceu cego"],
  ["JHN",11,17,44,"Jesus e Lázaro"], ["JHN",20,11,18,"Maria Madalena no jardim"],
  ["MAT",14,22,33,"Jesus caminha sobre as águas"], ["MAT",7,24,27,"A casa construída sobre a rocha"],
  ["MRK",10,13,16,"Jesus acolhe as crianças"],
  ["MRK",10,46,52,"Bartimeu à beira do caminho"], ["MRK",12,41,44,"A oferta da viúva"],
  ["ACT",2,1,13,"O dia de Pentecostes"], ["ACT",16,25,34,"Paulo e Silas na prisão"],
  ["ACT",9,36,42,"A história de Tabita"], ["RUT",1,6,18,"Rute e Noemi"],
  ["GEN",45,1,15,"José reencontra seus irmãos"], ["EXO",2,1,10,"Moisés no rio"],
  ["JON",3,1,10,"Jonas em Nínive"], ["DAN",6,16,23,"Daniel na cova dos leões"],
];
const root = resolve(import.meta.dirname, "..");
const index = JSON.parse(readFileSync(resolve(root, "mobile/src/generated/bible-blivre/index.json"), "utf8"));
const rows = selections.map(([book, chapter, start, end, name], ordinal) => {
  const data = JSON.parse(readFileSync(resolve(root, `mobile/src/generated/bible-blivre/${book}.json`), "utf8"));
  const verses = data.chapters[String(chapter)].filter((v) => Number(v.number) >= start && Number(v.number) <= end);
  if (verses.length !== end - start + 1 || verses.some((v,i) => Number(v.number) !== start+i || !v.text?.trim()))
    throw Error(`Incomplete passage ${book} ${chapter}:${start}-${end}`);
  const reference = `${data.book.name} ${chapter}:${start}–${end}`;
  const id = `biblia-livre-${book.toLowerCase()}-${chapter}-${start}-${end}`;
  const item = {
    id, type: "stories", origin: "publisher", lang: "pt", sourceCountry: "BR", rightsStatus: "licensed",
    source: "Bíblia Livre · edição protestante", author: "Diego Santos, Mario Sérgio e Marco Teles",
    title: { pt: `${name} · ${reference}` },
    summary: { pt: verses.slice(0, 2).map((v) => `${v.number}. ${v.text}`).join("\n\n") },
    body: { pt: `${verses.map((v) => `${v.number}. ${v.text}`).join("\n\n")}\n\n${index.attribution} ${index.licenseUrl}` },
    tags: ["Bíblia", "História bíblica"],
    url: `https://ebible.org/porbr2018/${book}${String(chapter).padStart(2,"0")}.htm`,
    license: index.attribution, licenseUrl: index.licenseUrl,
    resources: [["read", "Fonte da Bíblia Livre", "https://sites.google.com/site/biblialivre/"], ["read", "eBible", index.publisherRightsUrl]],
  };
  const json = JSON.stringify(item);
  if (json.includes("$story$")) throw Error("Unsafe SQL delimiter");
  return `(${ordinal+1}, $story$${json}$story$::jsonb)`;
});
writeFileSync(resolve(root, "supabase/seeds/brazilian_bible_stories.generated.sql"), `-- Generated by scripts/build-brazilian-bible-stories.mjs; do not edit.\ninsert into private.portuguese_bible_story_pool (ordinal, data) values\n${rows.join(",\n")};\n`);
console.log(`Prepared ${rows.length} complete Bible narratives.`);
